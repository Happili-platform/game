AUTH_MODES = {
    'custom_registry': ['push_oidc'],
    'github_inventory': ['legacy'],
    'atlassian_rovo_mcp': ['legacy'],
    'microsoft_foundry': ['legacy', 'entra_shared_app'],
    'google_agent_engine': ['legacy', 'google_impersonate'],
    'aws_agentcore': ['legacy', 'aws_assume_role'],
    'aws_bedrock_classic': ['legacy', 'aws_assume_role'],
}


def validate_auth_config(provider: str, mode: str, values: dict | None,
                         existing: dict | None = None) -> tuple[str, dict[str, str]]:
    """Validate externally visible cloud target settings. Never accept raw token source URLs."""
    if mode not in AUTH_MODES.get(provider, []):
        raise ValueError('Authentication mode is not supported by this provider')
    values = values or {}
    if not isinstance(values, dict):
        raise ValueError('Authentication settings must be an object')
    if mode == 'push_oidc':
        if values:
            raise ValueError('Private registry push mode has no credentials')
        return mode, {}
    if mode == 'legacy':
        if values:
            raise ValueError('Legacy mode has no workload configuration fields')
        return mode, {}
    if mode == 'aws_assume_role':
        if set(values) not in ({'role_arn'}, {'role_arn', 'external_id'}):
            raise ValueError('AWS requires a role ARN')
        role_arn = values.get('role_arn', '')
        if not isinstance(role_arn, str) or not re.fullmatch(r'arn:aws(-us-gov|-cn)?:iam::\d{12}:role/[A-Za-z0-9+=,.@_/-]{1,300}', role_arn):
            raise ValueError('Invalid AWS role ARN')
        # External ID never comes from the browser; retain the server-generated ID on edit.
        current_id = (existing or {}).get('external_id')
        if values.get('external_id') and values['external_id'] != current_id:
            raise ValueError('External ID is generated by GAME and cannot be edited')
        return mode, {'role_arn': role_arn, 'external_id': current_id or secrets.token_urlsafe(32)}
    if mode == 'google_impersonate':
        if set(values) != {'service_account_email'}:
            raise ValueError('Google requires service_account_email')
        email = values.get('service_account_email')
        if not isinstance(email, str) or not re.fullmatch(r'[A-Za-z0-9._-]{3,150}@[a-z][a-z0-9-]{5,62}\.iam\.gserviceaccount\.com', email):
            raise ValueError('Invalid Google service account email')
        return mode, {'service_account_email': email}
    if mode == 'entra_shared_app':
        if set(values) != {'tenant_id'} or not isinstance(values.get('tenant_id'), str) or not re.fullmatch(
                r'[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}', values['tenant_id']):
            raise ValueError('Entra shared app requires a tenant GUID')
        return mode, {'tenant_id': values['tenant_id'].lower()}
    raise ValueError('Unsupported authentication mode')



class DiscoveryError(Exception):
    """Safe, user-facing connector error; no low-level secrets or access tokens."""


@dataclass(frozen=True)
class DiscoveredAgent:
    external_id: str
    name: str
    provider: str
    description: str = ""
    provider_status: str = "unknown"


def validate_scope(provider: str, scope: dict[str, Any]) -> dict[str, str]:
    if provider not in IMPLEMENTED:
        raise ValueError("Provider is not available for live discovery yet")
    if not isinstance(scope, dict):
        raise ValueError("Scope must be an object")
    allowed = {
        "custom_registry": {"registry_name"},
        "github_inventory": {"organization"},
        "atlassian_rovo_mcp": {"endpoint"},
        "microsoft_foundry": {"project_endpoint"},
        "google_agent_engine": {"project_id", "location"},
        "aws_agentcore": {"region"},
        "aws_bedrock_classic": {"region"},
    }[provider]
    if set(scope) != allowed or not all(isinstance(v, str) and v.strip() for v in scope.values()):
        raise ValueError("Required scope fields: " + ", ".join(sorted(allowed)))
    normalized = {k: v.strip() for k, v in scope.items()}
    if provider == 'github_inventory':
        if not re.fullmatch(r'[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?', normalized['organization']):
            raise ValueError('Invalid GitHub organization')
    if provider == 'atlassian_rovo_mcp':
        if normalized['endpoint'] != 'https://mcp.atlassian.com/v2/mcp':
            raise ValueError('Only the official Atlassian Rovo MCP v2 endpoint is supported')
    if provider == 'custom_registry':
        if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._:-]{0,100}', normalized['registry_name']):
            raise ValueError('Invalid registry namespace')
    if provider == "microsoft_foundry":
        p = urlparse(normalized["project_endpoint"])
        if (p.scheme != "https" or p.port is not None or p.username or p.password
                or not p.hostname or not p.hostname.endswith(".services.ai.azure.com")
                or not re.fullmatch(r"/api/projects/[A-Za-z0-9_-]+/?", p.path)
                or p.query or p.fragment):
            raise ValueError("Use a Microsoft Foundry HTTPS project endpoint (*.services.ai.azure.com/api/projects/NAME)")
        normalized["project_endpoint"] = normalized["project_endpoint"].rstrip("/")
    elif provider == "google_agent_engine":
        if not re.fullmatch(r"[a-z][a-z0-9-]{4,62}", normalized["project_id"]):
            raise ValueError("Invalid Google Cloud project ID")
        if not re.fullmatch(r"[a-z]+(?:-[a-z]+)*[0-9]+", normalized["location"]):
            raise ValueError("Invalid Google Cloud location")
    elif provider in ('aws_agentcore', 'aws_bedrock_classic'):
        if not re.fullmatch(r"[a-z]{2}(?:-[a-z]+)+-[0-9]+", normalized["region"]):
            raise ValueError("Invalid AWS region")
    return normalized


def _azure(connection: dict, azure_credentials: dict[str, str] | None = None) -> list[DiscoveredAgent]:
    # Explicit service-principal credentials or managed identity; no Azure CLI dependency.
    prefix = connection["env_prefix"]
    try:
        from azure.identity import ClientSecretCredential, ManagedIdentityCredential
    except ImportError as exc:
        raise DiscoveryError("Install optional connector dependency azure-identity") from exc
    if connection.get('auth_mode') == 'entra_shared_app':
        tenant = connection['auth_config']['tenant_id']
        client = os.getenv('GAME_AZURE_CLIENT_ID')
        secret = os.getenv('GAME_AZURE_CLIENT_SECRET')
        if not client or not secret:
            raise DiscoveryError('Shared Entra app workload credentials are not configured on the server')
    elif azure_credentials:
        tenant = azure_credentials["tenant_id"]
        client = azure_credentials["client_id"]
        secret = azure_credentials["client_secret"]
    else:
        tenant, client, secret = (os.getenv(f"{prefix}_AZURE_{name}") for name in ("TENANT_ID", "CLIENT_ID", "CLIENT_SECRET"))
    if tenant and client and secret:
        credential = ClientSecretCredential(tenant, client, secret)
    elif os.getenv(f"{prefix}_AZURE_USE_MANAGED_IDENTITY") == "true":
        credential = ManagedIdentityCredential(client_id=client or None)
    else:
        raise DiscoveryError("Configure Entra service-principal environment variables or enable managed identity")
    endpoint = connection["scope"]["project_endpoint"]
    agents: list[DiscoveredAgent] = []
    try:
        token = credential.get_token("https://ai.azure.com/.default").token
        url = f"{endpoint}/agents"
        params = {"api-version": "v1", "limit": 100}
        with httpx.Client(timeout=20, follow_redirects=False, trust_env=False) as http:
            for _ in range(100):
                response = http.get(url, params=params, headers={"Authorization": f"Bearer {token}", "Accept": "application/json"})
                response.raise_for_status()
                data = response.json()
                items = data.get("data", data.get("agents", []))
                if not isinstance(items, list):
                    raise DiscoveryError("Microsoft response did not include an agent list")
                for item in items:
                    name = item.get("name") or item.get("id")
                    if name:
                        agents.append(DiscoveredAgent(str(item.get("id") or name), str(name), "Microsoft Foundry", str(item.get("description") or "")[:500], str(item.get("status") or "unknown")))
                marker = data.get("next_page_token") or data.get("nextPageToken")
                if not marker and data.get("has_more") and items:
                    marker = items[-1].get("id") or items[-1].get("name")
                if not marker or marker == params.get("after"):
                    return agents
                params["after"] = marker
            raise DiscoveryError("Microsoft pagination limit reached; scope must be narrowed")
    except httpx.HTTPStatusError as exc:
        raise DiscoveryError(f"Microsoft Foundry API returned HTTP {exc.response.status_code}; check RBAC and project endpoint") from exc
    except (httpx.RequestError, ValueError) as exc:
        raise DiscoveryError("Microsoft Foundry request failed; verify network and API response") from exc
    finally:
        credential.close()


def _verified_google_project_number(
    project_id: str,
    access_token: str,
) -> str:
    """Verify the project-ID/number alias using authenticated Google API."""
    import json
    from urllib.error import HTTPError, URLError
    from urllib.request import Request, urlopen

    url = (
        "https://cloudresourcemanager.googleapis.com/v3/"
        f"projects/{project_id}"
    )
    request = Request(
        url,
        headers={
            "Authorization": f"Bearer {access_token}",
            "Accept": "application/json",
        },
    )

    try:
        with urlopen(request, timeout=20) as response:
            payload = json.load(response)
    except (HTTPError, URLError, TimeoutError, OSError,
            ValueError, TypeError):
        raise DiscoveryError(
            "Google project-number verification failed"
        ) from None

    if not isinstance(payload, dict):
        raise DiscoveryError(
            "Google project identity response is invalid"
        )

    name = payload.get("name", "")
    number = (
        name.removeprefix("projects/")
        if isinstance(name, str)
        and name.startswith("projects/")
        else ""
    )

    if (
        payload.get("projectId") != project_id
        or not re.fullmatch(r"[1-9][0-9]*", number)
    ):
        raise DiscoveryError(
            "Google project identity does not match configured scope"
        )

    return number


def _google(
    connection: dict,
    google_credentials: dict | None = None,
    *,
    include_receipt: bool = False,
):
    """Google Agent Engine discovery with stage-specific sanitized errors.

    Uses the standard-library HTTPS transport to honor the same system proxy
    configuration as Google authentication and the standalone diagnostic probe.
    No access tokens or credential contents appear in error messages.
    """
    try:
        import google.auth
        from google.auth.transport.requests import Request
        from google.oauth2 import service_account
    except ImportError as exc:
        raise DiscoveryError("Install optional connector dependency google-auth") from exc

    from urllib.error import HTTPError, URLError
    from urllib.parse import urlencode
    from urllib.request import Request as HttpRequest, urlopen
    import json

    scope = connection["scope"]
    location = scope["location"]
    base_url = (
        f"https://{location}-aiplatform.googleapis.com/v1/"
        f"projects/{scope['project_id']}/locations/{location}/reasoningEngines"
    )
    scopes = ["https://www.googleapis.com/auth/cloud-platform"]
    try:
        if connection.get('auth_mode') == 'google_impersonate':
            from google.auth import impersonated_credentials
            source, _ = google.auth.default(scopes=scopes)
            credentials = impersonated_credentials.Credentials(
                source_credentials=source,
                target_principal=connection['auth_config']['service_account_email'],
                target_scopes=scopes, lifetime=1800)
        elif google_credentials is not None:
            credentials = service_account.Credentials.from_service_account_info(
                google_credentials, scopes=scopes
            )
        else:
            credentials, _ = google.auth.default(scopes=scopes)
    except Exception:
        raise DiscoveryError(
            "Google service-account credentials could not be loaded; re-save the complete JSON key"
        ) from None

    try:
        credentials.refresh(Request())
        if not credentials.token:
            raise ValueError("Missing OAuth access token")
    except Exception:
        raise DiscoveryError(
            "Google OAuth token exchange failed; check credentials and outbound HTTPS access"
        ) from None

    agents: list[DiscoveredAgent] = []
    page_token = None
    for _ in range(100):
        params = {"pageSize": 100}
        if page_token:
            params["pageToken"] = page_token
        url = f"{base_url}?{urlencode(params)}"
        request = HttpRequest(
            url,
            headers={
                "Authorization": f"Bearer {credentials.token}",
                "Accept": "application/json",
            },
        )
        try:
            with urlopen(request, timeout=20) as response:
                result = json.load(response)
        except HTTPError as exc:
            raise DiscoveryError(
                f"Google Agent Engine API returned HTTP {exc.code}; check project, location, API enablement and IAM"
            ) from None
        except (URLError, TimeoutError, OSError):
            raise DiscoveryError(
                "Google Agent Engine HTTPS request failed; check network and proxy configuration"
            ) from None
        except (ValueError, TypeError, UnicodeError):
            raise DiscoveryError(
                "Google Agent Engine API returned an invalid JSON response"
            ) from None

        if not isinstance(result, dict) or not isinstance(result.get("reasoningEngines", []), list):
            raise DiscoveryError("Google Agent Engine API response has an unexpected format")
        for item in result.get("reasoningEngines", []):
            if not isinstance(item, dict):
                continue
            resource = item.get("name")
            if resource:
                agents.append(DiscoveredAgent(
                    str(resource),
                    str(item.get("displayName") or str(resource).rsplit("/", 1)[-1]),
                    "Google Agent Engine",
                    str(item.get("description") or "")[:500],
                ))
        marker = result.get("nextPageToken")
        if marker == page_token and marker:
            raise DiscoveryError(
                "Google discovery returned a repeated pagination token"
            )
        if not marker:
            if not include_receipt:
                return agents

            # This point is reachable only after OAuth refresh and
            # successful completion of all provider API pages.
            from .discovery_provenance import _issue_connector_receipt
            from .identity import IdentityError

            verified_number = None
            numeric_projects = set()

            resource_pattern = re.compile(
                r"projects/([^/]+)/locations/([^/]+)/"
                r"reasoningEngines/([A-Za-z0-9_-]+)"
            )

            for agent in agents:
                match = resource_pattern.fullmatch(agent.external_id)
                if not match:
                    raise DiscoveryError(
                        "Google discovery returned an invalid resource"
                    )

                resource_project, resource_location, _ = match.groups()
                if resource_location != location:
                    raise DiscoveryError(
                        "Google discovery returned a different location"
                    )

                if resource_project != scope["project_id"]:
                    if not re.fullmatch(r"[1-9][0-9]*", resource_project):
                        raise DiscoveryError(
                            "Google discovery returned a different project"
                        )
                    numeric_projects.add(resource_project)

            if numeric_projects:
                verified_number = _verified_google_project_number(
                    scope["project_id"],
                    credentials.token,
                )
                if numeric_projects != {verified_number}:
                    raise DiscoveryError(
                        "Google discovery project identity mismatch"
                    )

            try:
                receipt = _issue_connector_receipt(
                    connection,
                    agents,
                    verified_project_number=verified_number,
                )
            except IdentityError as exc:
                raise DiscoveryError(
                    "Google discovery identity verification failed"
                ) from exc

            return agents, receipt

        page_token = marker
    raise DiscoveryError("Google pagination limit reached; narrow the project scope")


def _aws(connection: dict, aws_credentials: dict[str, str] | None = None) -> list[DiscoveredAgent]:
    try:
        import boto3
        from botocore.exceptions import BotoCoreError, ClientError, NoCredentialsError
    except ImportError as exc:
        raise DiscoveryError("Install optional connector dependency boto3") from exc
    prefix = connection["env_prefix"]
    profile = os.getenv(f"{prefix}_AWS_PROFILE")
    if connection.get('auth_mode') == 'aws_assume_role':
        # Source identity comes from the trusted SaaS host workload role.
        # Fresh AssumeRole on every discovery: no static customer STS credentials.
        source = boto3.Session(region_name=connection['scope']['region'])
        try:
            sts = source.client('sts')
            response = sts.assume_role(
                RoleArn=connection['auth_config']['role_arn'],
                RoleSessionName='GAME-' + connection['id'][-12:],
                ExternalId=connection['auth_config']['external_id'],
                DurationSeconds=900,
            )
            sts.close()
            temp = response['Credentials']
            session = boto3.Session(
                aws_access_key_id=temp['AccessKeyId'],
                aws_secret_access_key=temp['SecretAccessKey'],
                aws_session_token=temp['SessionToken'],
                region_name=connection['scope']['region'],
            )
        except Exception:
            raise DiscoveryError('AWS STS AssumeRole failed; verify workload source identity, role trust and External ID') from None
    elif aws_credentials:
        session = boto3.Session(
            aws_access_key_id=aws_credentials["access_key_id"],
            aws_secret_access_key=aws_credentials["secret_access_key"],
            aws_session_token=aws_credentials["session_token"],
            region_name=connection["scope"]["region"],
        )
    else:
        session = boto3.Session(profile_name=profile or None, region_name=connection["scope"]["region"])
    core = connection["provider"] == "aws_agentcore"
    client = session.client("bedrock-agentcore-control" if core else "bedrock-agent")
    result: list[DiscoveredAgent] = []
    token = None
    try:
        for _ in range(100):
            kwargs = {"maxResults": 100}
            if token:
                kwargs["nextToken"] = token
            data = client.list_agent_runtimes(**kwargs) if core else client.list_agents(**kwargs)
            for item in data.get("agentRuntimes" if core else "agentSummaries", []):
                name = item.get("agentRuntimeName" if core else "agentName")
                external = item.get("agentRuntimeArn" if core else "agentId")
                if external and name:
                    result.append(DiscoveredAgent(str(external), str(name), "AWS Bedrock AgentCore" if core else "AWS Bedrock Agents Classic", str(item.get("description") or "")[:500], str(item.get("status" if core else "agentStatus") or "unknown")))
            new_token = data.get("nextToken")
            if not new_token or new_token == token:
                return result
            token = new_token
        raise DiscoveryError("AWS pagination limit reached")
    except ClientError as exc:
        # Do not pass AWS exception strings through to the frontend: some include request identifiers.
        code = str((exc.response.get("Error") or {}).get("Code", ""))
        if code in {"ExpiredToken", "ExpiredTokenException", "RequestExpired"}:
            raise DiscoveryError("AWS temporary credentials have expired; update the saved credentials") from exc
        if code in {"InvalidClientTokenId", "UnrecognizedClientException", "InvalidToken"}:
            raise DiscoveryError("AWS credentials are invalid; replace the saved credentials") from exc
        if code in {"AccessDenied", "AccessDeniedException", "UnauthorizedOperation"}:
            raise DiscoveryError("AWS discovery access denied; check read-only IAM permissions") from exc
        raise DiscoveryError("AWS discovery failed; check credentials, IAM permissions and region") from exc
    except (BotoCoreError, NoCredentialsError) as exc:
        raise DiscoveryError("AWS discovery failed; check credentials, IAM permissions and region") from exc
    finally:
        client.close()



def discover_google_with_provenance(
    connection: dict,
    google_credentials: dict | None = None,
):
    """Return agents and an internally issued discovery receipt.

    Unlike the ordinary discover() API, the receipt is issued
    inside Google's authenticated, paginated discovery path.
    No receipt is issued for incomplete or failed discovery.
    """
    if connection.get("provider") != "google_agent_engine":
        raise DiscoveryError(
            "Verified discovery is not enabled for this provider"
        )
    return _google(
        connection,
        google_credentials=google_credentials,
        include_receipt=True,
    )


def discover(connection: dict, azure_credentials: dict[str, str] | None = None,
             aws_credentials: dict[str, str] | None = None,
             google_credentials: dict | None = None) -> list[DiscoveredAgent]:
    provider = connection["provider"]
    if provider == "microsoft_foundry":
        return _azure(connection, azure_credentials=azure_credentials)
    if provider == "google_agent_engine":
        return _google(connection, google_credentials=google_credentials)
    if provider in {"aws_agentcore", "aws_bedrock_classic"}:
        return _aws(connection, aws_credentials=aws_credentials)
    raise DiscoveryError("Connector not implemented")
